def build():
    d = Doc("Team Charter & Workplan", "How Group 4 is organised, who owns what, and how we prove every requirement of the brief is met",
            "Whole team", "00-Team")
    d.h1("1. Team and roles (4 members)")
    d.table(["ID", "Name", "Role", "Owns", "Sessions"], [(t["id"], t["name"], t["role"], t["owns"], t["sessions"]) for t in facts.TEAM],
            widths=[1.0, 2.2, 4.8, 7.4, 1.6], size=8.5)
    d.p(facts.CEO_NOTE)
    d.callout("To swap roles, swap the names in src/facts.py (TEAM) and run 'python src/build_all.py'; every document and deck updates at once. "
              "Each member must be able to explain every file they own (individual viva).", kind="info", title="Names")
    d.h1("2. RACI")
    d.table(["Deliverable", "{M1}", "{M2}", "{M3}", "{M4}"], RACI_ROWS, widths=[9.0, 2.0, 2.0, 2.0, 2.0], size=8.5)
    d.p("R = does the work, A = accountable (signs off), C = consulted, I = informed.", size=8.5, italic=True)
    d.h1("3. Four-week workplan")
    d.table(["Week", "Sessions", "Work", "Output"], PLAN, widths=[1.6, 2.2, 9.6, 3.6], size=8.5)
    d.h1("4. Weekly stand-up log (10 minutes with the instructor)")
    d.table(["Week", "Done since last stand-up (each member)", "Next week", "Blockers / help needed"], [
        ("1 (example)", "{M1}: dataset + segments; {M2}: KB outline; {M3}: peer chosen (S.P. Apparels); {M4}: value chain + 2x2", "Personas; Agent build; AR summary; forecast data",
         "Which no-code Agent tool the class may use"),
        ("2", "", "", ""), ("3", "", "", ""), ("4", "", "", ""),
    ], widths=[2.0, 7.0, 4.4, 3.6], size=8.5)
    d.h1("5. AI-use register (summary of all prompt logs)")
    d.table(["Area", "What AI was used for", "Logged prompts", "Key output rejected", "Human owner"], AI_REGISTER, widths=[2.0, 5.4, 2.0, 5.6, 2.0], size=8.5)
    d.callout("The raw outputs in the prompt logs were generated with Claude (Anthropic) when this project pack was drafted. If your instructor "
              "expects logs from your own tools, re-run each prompt (they are written out in full), paste your own raw output, and keep the edit "
              "rationale. The rationale is what the viva tests.", kind="warn", title="Honesty note")
    d.h1("6. Ground rules: compliance check")
    d.table(["Rule", "How we comply", "Status"], GROUND, widths=[4.2, 9.6, 3.2], size=8.5, first_col_bold=True)
    d.h1("7. Submission checklist: brief -> file")
    d.table(["Phase", "Requirement", "Where"], CHECKLIST, widths=[2.2, 8.4, 6.4], size=8)
    return d.save(ROOT / "00_Team_and_Project_Management" / "Team_Charter_and_Workplan.docx")


if __name__ == "__main__":
    print(build())
